                    "# 5. TRI-COMPASS DELTA-ORIGIN: PROMPT-CENTERING VETORIZADO EM 6 MS\n",
                    "# ==========================================================================\n",
                    "def center_groups_fast(X_dense: np.ndarray, g: np.ndarray) -> np.ndarray:\n",
                    "    _, inv = np.unique(g, return_inverse=True)\n",
                    "    counts = np.bincount(inv)\n",
                    "    sums = np.zeros((len(counts), X_dense.shape[1]), dtype=np.float32)\n",
                    "    np.add.at(sums, inv, X_dense)\n",
