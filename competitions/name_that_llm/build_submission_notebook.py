                    "        A[:, i] = new\n",
                    "        A[i, i] = -np.inf\n",
                    "        A[j] = -np.inf\n",
                    "        A[:, j] = -np.inf\n",
                    "        size[i] += size[j]\n",
                    "        alive[j] = False\n",
                    "        lab[lab == j] = i\n",
                    "    return lab\n"
