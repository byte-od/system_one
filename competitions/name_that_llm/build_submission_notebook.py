                    "    np.fill_diagonal(A, -np.inf)\n",
                    "    size = np.ones(n, np.int32)\n",
                    "    alive = np.ones(n, bool)\n",
                    "    lab = np.arange(n)\n",
                    "    while True:\n",
                    "        ok = (size[:, None] + size[None, :] <= cap) & alive[:, None] & alive[None, :]\n",
