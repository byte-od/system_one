                    "        k = int(np.argmax(M))\n",
                    "        i, j = divmod(k, n)\n",
                    "        if not np.isfinite(M[i, j]) or M[i, j] < thr:\n",
                    "            break\n",
                    "        new = (size[i] * A[i] + size[j] * A[j]) / (size[i] + size[j])\n",
